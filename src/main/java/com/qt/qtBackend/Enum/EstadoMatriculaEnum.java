package com.qt.qtBackend.Enum;

public enum EstadoMatriculaEnum {
    INSCRITO,       // El estudiante está inscrito en la institución
    MATRICULADO,    // La matrícula ha sido confirmada/paga
    EN_PAUSA,       // Matrícula temporalmente suspendida
    RETIRADO,       // El estudiante se retiró o canceló la matrícula
    EGRESADO,       // Finalizó estudios en la institución
    ANULADO         // Matrícula anulada por algún motivo administrativo
}
